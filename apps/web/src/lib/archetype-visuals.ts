const fallbackPalette = ["#7c6cff", "#3dd6b7", "#5fa8ff", "#e16bc7", "#f1a64c"];

function hash(value: string): number {
  return Array.from(value).reduce((total, character) => (total * 31 + character.charCodeAt(0)) >>> 0, 0);
}

export function getArchetypeVisual(deckId: string): ArchetypeVisual {
  return visuals[deckId] ?? { pokemonIds: [], accent: fallbackPalette[hash(deckId) % fallbackPalette.length] };
}

export function hasArchetypeArtwork(deckId: string): boolean {
  return Boolean(visuals[deckId]?.pokemonIds.length);
}

export function pokemonArtworkUrl(pokemonId: number): string {
  return `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/${pokemonId}.png`;
}
